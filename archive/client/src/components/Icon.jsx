export function resolveIcon(name) {
  return ICON_MAP[name] || null;
}

export default function Icon({ name, size = 16, color, style, className }) {
  const Cmp = ICON_MAP[name];
  if (!Cmp) return null;
  return (
    <Cmp
      width={size}
      height={size}
      aria-hidden="true"
      style={{ color, ...style }}
      className={className}
    />
  );
}
